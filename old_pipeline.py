"""# Nova secção"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

from rdkit import Chem, DataStructs
from rdkit.Chem import rdFingerprintGenerator

import umap.umap_ as umap

# Read the file line-by-line
with open("/content/chembl_frags.txt", "r", encoding="utf-8") as f:
    lines = f.readlines()

# Remove whitespace and empty lines
smiles = [
    line.strip()
    for line in lines
    if line.strip()
]

# Remove header if present
if smiles[0].lower() in ["molecule", "smiles"]:
    smiles = smiles[1:]

print(f"Total SMILES read from file: {len(smiles)}")
print(smiles[:5])

molecules = []
valid_smiles = []
invalid_smiles = []

for smi in smiles:

    mol = Chem.MolFromSmiles(smi)

    if mol is not None:
        molecules.append(mol)
        valid_smiles.append(smi)

    else:
        invalid_smiles.append(smi)

print(f"Total SMILES read: {len(smiles)}")
print(f"Valid molecules: {len(molecules)}")
print(f"Invalid SMILES: {len(invalid_smiles)}")

import random

random.seed(10)

# Randomly select indices
n_samples = min(10000, len(valid_smiles))

sampled_indices = random.sample(
    range(len(valid_smiles)),
    n_samples
)

# Select corresponding SMILES and molecules
sampled_smiles = [
    valid_smiles[i]
    for i in sampled_indices
]

sampled_molecules = [
    molecules[i]
    for i in sampled_indices
]

print(f"Total valid molecules: {len(valid_smiles)}")
print(f"Randomly sampled molecules: {len(sampled_molecules)}")

# Morgan fingerprint parameters
radius = 2
n_bits = 2048

fp_generator = rdFingerprintGenerator.GetMorganGenerator(
    radius=radius,
    fpSize=n_bits
)

fingerprints = []

for mol in sampled_molecules:

    # Generate Morgan fingerprint
    fp = fp_generator.GetFingerprint(mol)

    # Convert to NumPy array
    arr = np.zeros(
        (n_bits,),
        dtype=np.uint8
    )

    DataStructs.ConvertToNumpyArray(
        fp,
        arr
    )

    fingerprints.append(arr)


# Convert to NumPy matrix
fingerprints = np.array(
    fingerprints,
    dtype=np.uint8
)

print(
    "\nFingerprint matrix shape:",
    fingerprints.shape)

reducer = umap.UMAP(

    n_neighbors=15,

    min_dist=0.1,

    n_components=2,

    # Appropriate for binary Morgan fingerprints
    metric="jaccard",

    random_state=42,

    # Use multiple CPU cores
    n_jobs=-1
)


embedding = reducer.fit_transform(
    fingerprints
)

umap_df = pd.DataFrame({


    "UMAP1": embedding[:, 0],

    "UMAP2": embedding[:, 1]

})

plt.figure(
    figsize=(10, 8)
)

plt.scatter(

    umap_df["UMAP1"],

    umap_df["UMAP2"],

    s=10,

    alpha=0.6

)

plt.xlabel(
    "UMAP 1"
)

plt.ylabel(
    "UMAP 2"
)

plt.title(

    f"UMAP of Morgan Fingerprints\n"
    f"{len(valid_smiles):,} molecules"

)

plt.tight_layout()

plt.savefig(
    "/content/Morgan_UMAP.svg",
    format="svg",
    bbox_inches="tight"
)

plt.show()